/**
 * Kotlin/Native has no resource classpath, and a `simctl`-spawned simulator process must not
 * depend on host paths: the corpus the iOS benchmark binary reads is therefore embedded as
 * generated Kotlin source, exactly as `:kalligraphie:e2e` embeds its iOS fixtures. This task reads
 * the declared files and emits one chunked base64 string per resource.
 */
fun renderEmbeddedCorpus(entries: List<Pair<String, File>>): String {
    val sorted = entries.sortedBy { (resourcePath, _) -> resourcePath }
    val chunksByPath = sorted.associate { (resourcePath, file) ->
        resourcePath to Base64.getEncoder().encodeToString(file.readBytes()).chunked(32_768)
    }
    return buildString {
        appendLine("// @generated by :kalligraphie:bench:iosBenchmarkCorpus — do not edit.")
        appendLine("package org.graphiks.kalligraphie.bench.fixture")
        appendLine()
        appendLine("internal object IosFixtureCorpus {")
        appendLine("    internal val paths: Set<String> = setOf(")
        sorted.forEach { (resourcePath, _) -> appendLine("        \"$resourcePath\",") }
        appendLine("    )")
        appendLine()
        appendLine("    internal fun base64(relativePath: String): String = when (relativePath) {")
        chunksByPath.forEach { (resourcePath, chunks) ->
            appendLine("        \"$resourcePath\" -> listOf(")
            chunks.forEach { chunk -> appendLine("            \"$chunk\",") }
            appendLine("        ).joinToString(\"\")")
        }
        appendLine("        else -> error(\"The embedded benchmark corpus has no entry for \$relativePath.\")")
        appendLine("    }")
        appendLine("}")
    }
}

/**
 * The corpus the measurement reads, and nothing else: the four fixtures behind the COLR, SVG-in-OT,
 * EBDT bitmap and TrueType scenarios, plus the DejaVu and Amiri faces the paragraph profiles compose
 * with. `END_TO_END_LAYOUT` is declared present on iOS since the facades and the portable Unicode
 * analysis became `commonMain` code, so those profiles run here too and their fonts must travel with
 * them.
 */
val iosBenchmarkCorpus by tasks.registering {
    group = "benchmark"
    description = "Embeds the measurement corpus into the iOS benchmark binary."
    val fixtures = rootProject.layout.projectDirectory.dir("test-fixtures")
    val entries = listOf(
        "/fonts/bungee-color/BungeeColor-Regular.ttf" to fixtures.file("fonts/bungee-color/BungeeColor-Regular.ttf").asFile,
        "/fonts/twemoji-svginot-glyph5/TwitterColorEmoji-SVGinOT-15.1.0-glyph5.ttf.base64" to fixtures.file("fonts/twemoji-svginot-glyph5/TwitterColorEmoji-SVGinOT-15.1.0-glyph5.ttf.base64").asFile,
        "/fonts/skia-ebdt-format1/ebdt_fmt1.ttf" to fixtures.file("fonts/skia-ebdt-format1/ebdt_fmt1.ttf").asFile,
        "/fonts/liberation/LiberationSans-Regular.ttf" to fixtures.file("fonts/liberation/LiberationSans-Regular.ttf").asFile,
        "/fonts/dejavu/DejaVuSans.ttf" to fixtures.file("fonts/dejavu/DejaVuSans.ttf").asFile,
        "/fonts/amiri/Amiri-Regular.ttf" to fixtures.file("fonts/amiri/Amiri-Regular.ttf").asFile,
    )
    inputs.files(entries.map { (_, file) -> file }).withPropertyName("fixtureFiles")
    val outputDirectory = layout.buildDirectory.dir("generated/ios-benchmark-corpus/kotlin")
    outputs.dir(outputDirectory)
    doLast {
        val source = outputDirectory.get().asFile
            .resolve("org/graphiks/kalligraphie/bench/fixture/IosFixtureCorpus.kt")
        source.parentFile.mkdirs()
        source.writeText(renderEmbeddedCorpus(entries))
    }
}

/**
 * The measured commit travels to the instrumentation process as a class-path resource — the same
 * channel the corpus uses — because a process on the device cannot call git, the publication
 * contract refuses an unnamed commit, and the main compilation cannot see androidx.test's argument
 * surface.
 */
val androidBenchmarkIdentity by tasks.registering {
    group = "benchmark"
    description = "Writes the measured commit into the Android device-test APK."
    val outputDirectory = layout.buildDirectory.dir("generated/android-benchmark-identity")
    outputs.dir(outputDirectory)
    doLast {
        val commit = providers.exec {
            commandLine("git", "rev-parse", "HEAD")
            workingDir(rootDir)
        }.standardOutput.asText.get().trim()
        check(commit.matches(Regex("[0-9a-f]{40}"))) {
            "Could not identify the measured commit for the Android benchmark: $commit"
        }
        outputDirectory.get().asFile.apply { mkdirs() }
            .resolve("bench-identity.properties")
            .writeText("commit=$commit\n")
    }
}


/**
 * Spawns the `glyphBench` simulator binary and captures its report.
 *
 * kotlinx-benchmark's native backend skips every target whose Kotlin/Native target differs from
 * the build host (`NativeMultiplatformTasks.kt` returns before configuring anything), so the
 * simulator is served by this driver instead: the linked release executable runs on a booted
 * iPhone simulator through `xcrun simctl spawn --standalone`, the same way the Kotlin test
 * executor launches its simulator binaries. The task resolves an already-booted device first so a
 * warm simulator is reused, and hands the driver the measured commit through the environment — a
 * `simctl`-spawned process cannot call git itself.
 *
 * The task declares no outputs on purpose: a measurement that ran before is not a measurement that
 * is up to date.
 */
abstract class IosBenchmarkRunTask @Inject constructor(
    private val execOps: ExecOperations,
) : DefaultTask() {

    /** The linked `glyphBench` release executable this task spawns. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val benchmarkBinary: RegularFileProperty

    /** The repository root the measured commit is read from. */
    @get:Internal
    abstract val repositoryRoot: DirectoryProperty

    /** The JSONL observations the driver appends; truncated before each run. */
    @get:Internal
    abstract val observationsFile: RegularFileProperty

    /** The report the binary printed to stdout, kept next to the observations. */
    @get:Internal
    abstract val reportFile: RegularFileProperty

    @TaskAction
    fun runBenchmark() {
        val binary = benchmarkBinary.get().asFile
        check(binary.isFile) { "The iOS benchmark binary is missing: $binary." }
        val device = resolveIphoneDevice()
        bootDevice(device)
        val observations = observationsFile.get().asFile
        observations.parentFile.mkdirs()
        observations.delete()
        val output = ByteArrayOutputStream()
        execOps.exec {
            commandLine("xcrun", "simctl", "spawn", "--standalone", device, binary.absolutePath)
            environment("SIMCTL_CHILD_KALLIGRAPHIE_BENCH_COMMIT", measuredCommit())
            environment(
                "SIMCTL_CHILD_KALLIGRAPHIE_BENCH_OBSERVATIONS",
                observations.absolutePath,
            )
            standardOutput = output
        }
        val report = output.toString("UTF-8")
        reportFile.get().asFile.writeText(report)
        report.lineSequence().forEach { logger.lifecycle(it) }
    }

    /** A booted iPhone when one exists, else the first available one — never a fabricated device. */
    private fun resolveIphoneDevice(): String {
        val listing = capture("xcrun", "simctl", "list", "devices", "available")
        val devices = Regex("""iPhone.*\(([0-9A-Fa-f-]{36})\) \((Booted|Shutdown)\)""")
            .findAll(listing)
            .map { it.groupValues[1] to it.groupValues[2] }
            .toList()
        return devices.firstOrNull { (_, state) -> state == "Booted" }?.first
            ?: devices.firstOrNull()?.first
            ?: error("No available iPhone simulator was found; install a simulator runtime via Xcode.")
    }

    private fun bootDevice(device: String) {
        val boot = execOps.exec {
            commandLine("xcrun", "simctl", "boot", device)
            isIgnoreExitValue = true
        }
        if (boot.exitValue != 0) {
            logger.lifecycle("simctl boot did not start the device (usually 'already booted'); waiting on bootstatus.")
        }
        execOps.exec { commandLine("xcrun", "simctl", "bootstatus", device, "-b") }
    }

    private fun measuredCommit(): String {
        val output = ByteArrayOutputStream()
        val result = execOps.exec {
            commandLine("git", "rev-parse", "HEAD")
            workingDir = repositoryRoot.get().asFile
            standardOutput = output
            isIgnoreExitValue = true
        }
        val commit = output.toString("UTF-8").trim()
        check(result.exitValue == 0 && commit.matches(Regex("[0-9a-f]{40}"))) {
            "Could not identify the measured commit for the iOS benchmark."
        }
        return commit
    }

    private fun capture(vararg command: String): String {
        val output = ByteArrayOutputStream()
        execOps.exec {
            commandLine(*command)
            standardOutput = output
        }
        return output.toString("UTF-8")
    }
}

val iosSimulatorArm64Benchmark by tasks.registering(IosBenchmarkRunTask::class) {
    group = "benchmark"
    description = "Runs the portable measurement on the iOS simulator."
    val glyphBenchLink = kotlin.targets
        .named<KotlinNativeTarget>("iosSimulatorArm64")
        .flatMap { target -> target.binaries.getExecutable("glyphBench", NativeBuildType.RELEASE).linkTaskProvider }
    benchmarkBinary.set(
        glyphBenchLink.flatMap { link -> link.outputFile.map { path -> layout.projectDirectory.file(path.absolutePath) } },
    )
    dependsOn(glyphBenchLink)
    repositoryRoot.set(rootProject.layout.projectDirectory)
    observationsFile.set(layout.buildDirectory.file("bench/ios-observations.jsonl"))
    reportFile.set(layout.buildDirectory.file("bench/ios-report.md"))
}

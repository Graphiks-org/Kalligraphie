/**
 * The corpus the iOS simulator harness reads: embedded because Kotlin/Native has no resource class
 * path and the `simctl`-spawned test process does not inherit the Gradle environment.
 */
val iosFixtureCorpus by tasks.registering {
    group = "verification"
    description = "Embeds the iOS harness corpus into the iosSimulatorArm64Test binary."
    val entries = e2eHarnessCorpusEntries
    inputs.files(entries.map { (_, file) -> file }).withPropertyName("fixtureFiles")
    val outputDirectory = layout.buildDirectory.dir("generated/ios-fixture-corpus/kotlin")
    outputs.dir(outputDirectory)
    doLast {
        val source = outputDirectory.get().asFile
            .resolve("org/graphiks/kalligraphie/e2e/fixture/E2eFixtureCorpus.kt")
        source.parentFile.mkdirs()
        source.writeText(renderEmbeddedCorpus(entries, "iosFixtureCorpus"))
    }
}


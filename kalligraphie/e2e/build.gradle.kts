/**
 * Kotlin/Native and Kotlin/Wasm have no resource classpath: neither can read `test-fixtures/` the way
 * the JVM and Android ones do. The corpus they need is therefore embedded as generated Kotlin source,
 * exactly as `:kalligraphie:shaping` embeds its iOS fixtures: this task reads the declared files and
 * emits one chunked base64 string per resource.
 */
fun renderEmbeddedCorpus(entries: List<Pair<String, File>>, sourceTask: String): String {
    val sorted = entries.sortedBy { (resourcePath, _) -> resourcePath }
    val chunksByPath = sorted.associate { (resourcePath, file) ->
        resourcePath to Base64.getEncoder().encodeToString(file.readBytes()).chunked(32_768)
    }
    return buildString {
        appendLine("// @generated by :kalligraphie:e2e:$sourceTask — do not edit.")
        appendLine("package org.graphiks.kalligraphie.e2e.fixture")
        appendLine()
        appendLine("internal object E2eFixtureCorpus {")
        appendLine("    internal val paths: Set<String> = setOf(")
        sorted.forEach { (resourcePath, _) -> appendLine("        \"$resourcePath\",") }
        appendLine("    )")
        appendLine()
        appendLine("    internal fun base64(relativePath: String): String = when (relativePath) {")
        chunksByPath.forEach { (resourcePath, chunks) ->
            appendLine("        \"$resourcePath\" -> listOf(")
            chunks.forEach { chunk -> appendLine("            \"$chunk\",") }
            appendLine("        ).joinToString(\"\")")
        }
        appendLine("        else -> error(\"The embedded harness corpus has no entry for \$relativePath.\")")
        appendLine("    }")
        appendLine("}")
    }
}

